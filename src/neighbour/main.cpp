int main(int argc, char** argv)
{
    try {
        return coldpath::neighbour::Run(argc, argv);
    } catch (const std::exception& e) {
        std::fprintf(stderr, "neighbour: %s\n", e.what());
    } catch (...) {
        std::fprintf(stderr, "neighbour: unknown error\n");
    }
    return 2;
}
