constexpr uint64_t LogStepNs = 100'000'000;
constexpr int NopPerUnit = 256;
constexpr size_t LinesPerUnit = 1024;
constexpr size_t Line = 64;
constexpr size_t IoBlock = 4096;

volatile std::sig_atomic_t Stop = 0;

void OnSignal(int /*signal*/)
{
    Stop = 1;
}

void InstallSignals()
{
    // No SA_RESTART: waitpid and the sleeps return EINTR and the loop sees the stop.
    struct sigaction action{};
    action.sa_handler = OnSignal;
    sigaction(SIGTERM, &action, nullptr);
    sigaction(SIGINT, &action, nullptr);
}

size_t ParseSize(std::string_view text)
{
    size_t scale = 1;
    if (!text.empty()) {
        switch (text.back()) {
            case 'k':
            case 'K':
                scale = 1ULL << 10;
                break;
            case 'm':
            case 'M':
                scale = 1ULL << 20;
                break;
            case 'g':
            case 'G':
                scale = 1ULL << 30;
                break;
            default:
                break;
        }
    }
    if (scale != 1) {
        text.remove_suffix(1);
    }
    return ParseNumber<size_t>(text) * scale;
}

enum class EKind : uint8_t {
    Nop,
    Mem,
    Code,
    Io,
    Exec,
};

struct TOptions
{
    EKind Kind = EKind::Nop;
    std::string Load;
    size_t MemBytes = 0;
    double IoRate = 0;
    int Cpu = -1;
    std::string Counter;
    std::string WaitFile;
    std::string Log;
    std::string IoFile = "data/20190730.BX_ITCH_50";
    std::string Command;
    double DurationS = 0;
};

TOptions ParseOptions(int argc, char** argv)
{
    const TArgs args(argc,
        argv,
        {.Values = {"load", "cpu", "counter", "wait-file", "log", "io-file", "cmd", "duration"}, .Flags = {}});
    TOptions o;
    o.Load = args.Text("load", "");
    const std::string_view load = o.Load;
    if (load == "nop") {
        o.Kind = EKind::Nop;
    } else if (load.starts_with("mem:")) {
        o.Kind = EKind::Mem;
        o.MemBytes = std::max(Line, ParseSize(load.substr(4)));
    } else if (load == "code" || load == "code:128k") {
        o.Kind = EKind::Code;
    } else if (load.starts_with("io:")) {
        o.Kind = EKind::Io;
        o.IoRate = ParseNumber<double>(load.substr(3));
    } else if (load == "exec") {
        o.Kind = EKind::Exec;
    } else {
        throw std::invalid_argument("--load nop|mem:<size>|code|io:<reads/s>|exec, not '" + o.Load + "'");
    }
    o.Cpu = static_cast<int>(args.Int("cpu", -1));
    o.Counter = args.Text("counter", "");
    o.WaitFile = args.Text("wait-file", "");
    o.Log = args.Text("log", "");
    o.IoFile = args.Text("io-file", o.IoFile);
    o.Command = args.Text("cmd", "");
    o.DurationS = args.Double("duration", 0);
    if (o.Kind == EKind::Exec && o.Command.empty()) {
        throw std::invalid_argument("--load exec requires --cmd");
    }
    if (o.Kind == EKind::Io && o.IoRate <= 0) {
        throw std::invalid_argument("io:<reads/s> must be a positive number");
    }
    return o;
}

// Units done so far; with --counter it lives in a shared file that bench maps read-only.
class TCounter
{
public:
    explicit TCounter(const std::string& path)
    {
        if (path.empty()) {
            return;
        }
        const int fd = open(path.c_str(), O_RDWR | O_CREAT | O_TRUNC, 0644);
        if (fd < 0 || ftruncate(fd, sizeof(uint64_t)) != 0) {
            throw std::runtime_error("cannot open counter " + path);
        }
        void* map = mmap(nullptr, sizeof(uint64_t), PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
        close(fd);
        if (map == MAP_FAILED) {
            throw std::runtime_error("mmap " + path);
        }
        Value_ = static_cast<volatile uint64_t*>(map);
        *Value_ = 0;
    }

    ~TCounter()
    {
        if (Value_ != &Local_) {
            munmap(const_cast<uint64_t*>(Value_), sizeof(uint64_t));
        }
    }

    TCounter(const TCounter&) = delete;
    TCounter& operator=(const TCounter&) = delete;

    void Add()
    {
        *Value_ = *Value_ + 1;
    }

    uint64_t Get() const
    {
        return *Value_;
    }

private:
    volatile uint64_t Local_ = 0;
    // An aligned 8-byte store is atomic on x86, so bench never sees a torn value.
    volatile uint64_t* Value_ = &Local_;
};

class TWork
{
public:
    explicit TWork(const TOptions& options)
        : Options_(options)
    {
        if (options.Kind == EKind::Mem) {
            // Touched now, so page faults are over before the ready file appears.
            Buffer_.assign(options.MemBytes, 1);
        }
        if (options.Kind == EKind::Io) {
            Fd_ = open(options.IoFile.c_str(), O_RDONLY | O_DIRECT);
            struct stat st{};
            if (Fd_ < 0 || fstat(Fd_, &st) != 0 || st.st_size < static_cast<off_t>(IoBlock)) {
                throw std::runtime_error("O_DIRECT: cannot open " + options.IoFile);
            }
            Blocks_ = static_cast<uint64_t>(st.st_size) / IoBlock;
            IoBuffer_.reset(static_cast<uint8_t*>(std::aligned_alloc(IoBlock, IoBlock)));
            PeriodNs_ = static_cast<uint64_t>(1e9 / options.IoRate);
        }
    }

    ~TWork()
    {
        if (Fd_ >= 0) {
            close(Fd_);
        }
    }

    TWork(const TWork&) = delete;
    TWork& operator=(const TWork&) = delete;

    // One unit of work; false if a stop interrupted it.
    bool Unit()
    {
        switch (Options_.Kind) {
            case EKind::Nop:
                for (int i = 0; i < NopPerUnit; ++i) {
                    _mm_pause();
                }
                return true;
            case EKind::Mem:
                for (size_t i = 0; i < LinesPerUnit && i * Line < Buffer_.size(); ++i) {
                    ++Buffer_[Pos_];
                    Pos_ = Pos_ + Line < Buffer_.size() ? Pos_ + Line : 0;
                }
                return true;
            case EKind::Code:
                State_ = handler::RunCode(State_);
                return true;
            case EKind::Io:
                return Read();
            case EKind::Exec:
                return Exec();
        }
        return false;
    }

    std::string Describe() const
    {
        switch (Options_.Kind) {
            case EKind::Nop:
                return std::format("nop: unit = {} pause", NopPerUnit);
            case EKind::Mem:
                return std::format("mem: writes over {} KB, unit = {} lines", Buffer_.size() >> 10, LinesPerUnit);
            case EKind::Code:
                return "code: unit = one RunCode call (128 KB of code)";
            case EKind::Io:
                return std::format("io: {:.0f} reads/s of 4 KB with O_DIRECT from {}",
                    Options_.IoRate,
                    Options_.IoFile);
            case EKind::Exec:
                return "exec: unit = one completed command: " + Options_.Command;
        }
        return "";
    }

    uint64_t Sink() const
    {
        return State_;
    }

private:
    struct TFree
    {
        void operator()(uint8_t* p) const
        {
            std::free(p);
        }
    };

    const TOptions& Options_;
    std::vector<uint8_t> Buffer_;
    size_t Pos_ = 0;
    uint64_t State_ = 1;
    int Fd_ = -1;
    uint64_t Blocks_ = 0;
    std::unique_ptr<uint8_t, TFree> IoBuffer_;
    uint64_t PeriodNs_ = 0;
    uint64_t Next_ = 0;

    bool Read()
    {
        const uint64_t now = MonotonicNs();
        Next_ = Next_ + PeriodNs_ < now ? now : Next_ + PeriodNs_;
        SleepUntil(Next_);
        State_ = State_ * 6364136223846793005ULL + 1442695040888963407ULL;
        const auto offset = static_cast<off_t>((State_ >> 17) % Blocks_ * IoBlock);
        return pread(Fd_, IoBuffer_.get(), IoBlock, offset) == static_cast<ssize_t>(IoBlock);
    }

    bool Exec()
    {
        const uint64_t start = MonotonicNs();
        const pid_t pid = fork();
        if (pid == 0) {
            setpgid(0, 0);
            execl("/bin/sh", "sh", "-c", Options_.Command.c_str(), static_cast<char*>(nullptr));
            _exit(127);
        }
        if (pid < 0) {
            return false;
        }
        int status = 0;
        while (waitpid(pid, &status, 0) < 0) {
            if (errno != EINTR) {
                return false;
            }
            if (Stop != 0) {
                kill(-pid, SIGTERM);
            }
        }
        const bool ok = Stop == 0 && WIFEXITED(status) && WEXITSTATUS(status) == 0;
        Println("command: {:.3f} s{}",
            static_cast<double>(MonotonicNs() - start) / 1e9,
            ok ? "" : std::format(", status {}", status));
        return ok;
    }
};

void WaitForFile(const std::string& path)
{
    if (path.empty()) {
        return;
    }
    while (Stop == 0 && access(path.c_str(), F_OK) != 0) {
        SleepUntil(MonotonicNs() + 1'000'000);
    }
}

int Run(int argc, char** argv)
{
    const TOptions options = ParseOptions(argc, argv);
    InstallSignals();
    PinToCpu(options.Cpu);
    // Explicitly an ordinary task at nice 0, whatever the parent was: bench (SCHED_FIFO) must preempt it.
    const sched_param param{.sched_priority = 0};
    if (sched_setscheduler(0, SCHED_OTHER, &param) != 0) {
        std::perror("SCHED_OTHER");
    }
    TCounter counter(options.Counter);
    TWork work(options);
    const TFilePtr log = options.Log.empty() ? nullptr : OpenFile(options.Log, "w");
    Println("neighbour: {}; core {}; counter {}", work.Describe(), options.Cpu, options.Counter);
    const uint64_t launched = MonotonicNs();
    WaitForFile(options.WaitFile);
    const uint64_t start = MonotonicNs();
    Println("work started {:.1f} s after launch", static_cast<double>(start - launched) / 1e9);
    const uint64_t end = options.DurationS > 0 ? start + static_cast<uint64_t>(options.DurationS * 1e9) : UINT64_MAX;
    uint64_t nextLog = start + LogStepNs;
    uint64_t logged = 0;
    uint64_t now = start;
    while (Stop == 0 && now < end) {
        if (work.Unit()) {
            counter.Add();
        }
        now = MonotonicNs();
        if (log && now >= nextLog) {
            // Units per 100 ms interval: the neighbour's own speed must not drift within a run.
            const uint64_t done = counter.Get();
            Print(log.get(), "{:.1f} {}\n", static_cast<double>(now - start) / 1e6, done - logged);
            logged = done;
            nextLog = now - (now - start) % LogStepNs + LogStepNs;
        }
    }
    const double seconds = static_cast<double>(now - start) / 1e9;
    Println("total: load={} units={} seconds={:.3f} rate_per_s={:.1f} sink={}",
        options.Load,
        counter.Get(),
        seconds,
        seconds > 0 ? static_cast<double>(counter.Get()) / seconds : 0.0,
        work.Sink() & 1U);
    return 0;
}

