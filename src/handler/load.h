#pragma once

#include "handler/send.h"

#include <cstdint>
#include <string>
#include <vector>

// Handler size axis: work after the strategy fires — risk checks, model, generated code, order
// sending. The sizes are fixed at build time; with all three at 0 the load is compiled out.
#ifndef COLDPATH_CODE_KB
#define COLDPATH_CODE_KB 0
#endif
#ifndef COLDPATH_DATA_LINES
#define COLDPATH_DATA_LINES 0
#endif
#ifndef COLDPATH_SEND
#define COLDPATH_SEND 0
#endif
#define COLDPATH_LOAD (COLDPATH_CODE_KB > 0 || COLDPATH_DATA_LINES > 0 || COLDPATH_SEND > 0)

namespace coldpath::handler {

// Generated by gen-code.py: calls every generated function; the result depends on all of them.
uint64_t RunCode(uint64_t state);

class TLoad
{
public:
    bool Init(unsigned seed);
    // One pass per event. A dry run leaves the state unchanged and never touches the real order socket.
    void Run(int64_t signal, bool dryRun);
    // Data lines of a pass (this object with the order buffer, the model rows); fixed after Init.
    const std::vector<const void*>& Lines() const;
    uint64_t RealSends() const;
    std::string Describe() const;
    std::string Summary() const;

private:
    // No fills come back, so the position stays flat and the limits are never reached.
    int64_t Position_ = 0;
    int64_t MaxShares_ = 0;
    int64_t MaxPosition_ = 0;
    int64_t MaxNotional_ = 0;
    uint32_t RefPrice_ = 0;
    uint32_t MinPrice_ = 0;
    uint32_t MaxPrice_ = 0;
    bool Initialized_ = false;
    uint64_t Rejected_ = 0;
#if COLDPATH_CODE_KB > 0 || COLDPATH_DATA_LINES > 0
    uint64_t Sink_ = 0;
#endif
    std::vector<const void*> Lines_;
#if COLDPATH_SEND
    TOrderSender Sender_;
#endif
};

} // namespace coldpath::handler
