#!/usr/bin/env python3
"""Extra handler code for the size axis: N distinct noinline functions of ~128 bytes
(2 conditional branches each) and RunCode, which calls them all in a shuffled order.

    ./gen-code.py 32 -o build/gen/code_32.cpp      # 32 KB = 256 functions
"""
import argparse
import os
import random

FUNCTION_BYTES = 128

FUNCTION = """\
[[gnu::noinline]] uint64_t Code{i}(uint64_t s)
{{
    uint64_t x = (s ^ {k0:#018x}ULL) * {k1:#018x}ULL;
    if (((s >> {b0}) & 1U) != 0) {{
        x += x >> {r0};
        __asm__ volatile("");
    }} else {{
        x ^= {k2:#010x}U;
    }}
    if (((x >> {b1}) & 1U) != 0) {{
        x = (x ^ (x >> {r1})) * {k3:#018x}ULL;
        __asm__ volatile("");
    }} else {{
        x -= {k4:#010x}U;
    }}
    return x;
}}
"""


def generate(kb, seed):
    rng = random.Random(seed)
    count = kb * 1024 // FUNCTION_BYTES
    out = [
        f"// Generated by gen-code.py: {count} functions (~{kb} KB), seed {seed}. Do not edit.",
        "// The empty asm keeps each branch a real conditional jump instead of cmov. External linkage (and GCC's",
        "// -fno-toplevel-reorder) keeps the functions in source order, so the shuffled calls jump across the code.",
        "#include <cstdint>",
        "",
        "namespace coldpath::handler::code {",
        "",
    ]
    for i in range(count):
        # Distinct constants: no two functions are identical, so they cannot be folded (ICF).
        # k2 and k4 fit an imm32, which keeps the body under 128 bytes.
        k = [rng.getrandbits(64) | 1, rng.getrandbits(64) | 1, rng.getrandbits(31), rng.getrandbits(64) | 1,
             rng.getrandbits(31)]
        out.append(FUNCTION.format(i=i, k0=k[0], k1=k[1], k2=k[2], k3=k[3], k4=k[4],
                                   b0=rng.randrange(8, 56), b1=rng.randrange(8, 56),
                                   r0=rng.randrange(13, 41), r1=rng.randrange(13, 41)))
    order = list(range(count))
    rng.shuffle(order)
    out += ["} // namespace coldpath::handler::code", "", "namespace coldpath::handler {", "",
            "uint64_t RunCode(uint64_t state)", "{"]
    out += [f"    state = code::Code{i}(state);" for i in order]
    out += ["    return state;", "}", "", "} // namespace coldpath::handler", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("kb", type=int, help="size of the generated code, KB (128 bytes per function)")
    parser.add_argument("--seed", type=int, default=1, help="constants, branch bits and call order")
    parser.add_argument("-o", "--out", help="output file (default build/gen/code_<KB>.cpp)")
    args = parser.parse_args()
    if args.kb <= 0:
        parser.error("KB must be positive")
    path = args.out or f"build/gen/code_{args.kb}.cpp"
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write(generate(args.kb, args.seed))


if __name__ == "__main__":
    main()
